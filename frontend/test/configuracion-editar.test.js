import {test,after} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createServer} from 'vite';
import {fileURLToPath} from 'node:url';
import {createElement as h,act} from 'react';
const dom=new JSDOM('<!doctype html><div id="root"></div>',{url:'http://localhost:5173'});
for (const [k,v] of Object.entries({window:dom.window,document:dom.window.document,Event:dom.window.Event,FormData:dom.window.FormData,IS_REACT_ACT_ENVIRONMENT:true})) Object.defineProperty(globalThis,k,{value:v,configurable:true,writable:true});
const {createRoot}=await import('react-dom/client');
const vite=await createServer({root:fileURLToPath(new URL('../',import.meta.url)),server:{middlewareMode:true},appType:'custom',logLevel:'error'});
const {api}=await vite.ssrLoadModule('/src/services/api/cliente.js');
const {default:Configuracion}=await vite.ssrLoadModule('/src/modules/configuracion/Configuracion.jsx');
let valor='Taller', solicitud;
api.obtener=async()=>({opciones:[{id:'1',modulo:'vehiculos',campo:'origen',valor,activo:true,exclusiva:false}]});
api.pedir=async(ruta,opciones)=>{solicitud={ruta,body:JSON.parse(opciones.body)};valor=solicitud.body.valor;return {json:async()=>({})};};
const root=createRoot(document.getElementById('root'));
after(async()=>{await act(async()=>root.unmount());await vite.close();dom.window.close()});
test('editar cambia la opción y conserva el identificador sin modificar registros',async()=>{
 await act(async()=>{root.render(h(Configuracion));await new Promise(r=>setTimeout(r,20));});
 const editar=[...document.querySelectorAll('button')].find(b=>b.textContent==='Editar');
 await act(async()=>editar.click());
 const input=document.querySelector('#editar-opcion-1');
 const setter=Object.getOwnPropertyDescriptor(dom.window.HTMLInputElement.prototype,'value').set;
 await act(async()=>{input.focus();setter.call(input,'Taller central');input.dispatchEvent(new dom.window.Event('input',{bubbles:true}));});
 await act(async()=>document.querySelector('.configuracion-edicion').dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true})));
 assert.equal(solicitud.ruta,'/api/configuracion/editar');
 assert.deepEqual(solicitud.body,{id:'1',modulo:'vehiculos',campo:'origen',anterior:'Taller',valor:'Taller central'});
 assert.match(document.body.textContent,/Taller central/);
});
